import path from "node:path";
import process from "node:process";
import builtins from "builtin-modules";
import esbuild from "esbuild";

// Bundle only the engine facade we use. Resolving `@tsvsheet/tsvsheet` by its
// package entry pulls in `load.js`, whose `import.meta.url`/`node:fs` asset
// loading is dead code here (we instantiate from bytes read at runtime) yet
// still lands in the graph. Pointing the import straight at the `Engine`
// module keeps the bundle to exactly what runs.
const engineEntry = path.join(
	import.meta.dirname,
	"node_modules/@tsvsheet/tsvsheet/src/tsvsheet/engine.js",
);

// The @generated marker keeps bundle output out of the fleet lint gate
// (nicerobot/tools.build ci/typescript excludes files carrying it).
const banner = `/*
@generated THIS IS A GENERATED/BUNDLED FILE BY ESBUILD.
For the source, see https://github.com/tsvsheet/tsvsheet.obsidian
*/
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins,
		...builtins.map((name) => `node:${name}`),
	],
	alias: {
		"@tsvsheet/tsvsheet": engineEntry,
	},
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
